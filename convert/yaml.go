package convert

import (
	"fmt"
	"io"
	"strings"
)

// Tuning is the content of a libcamera software ISP tuning file.
type Tuning struct {
	// Source names what the data was generated from, for the header.
	Source []string
	// BlackLevel is on libcamera's 16-bit scale; 0 leaves it out.
	BlackLevel int
	CCMs       []CCM
	// ToneCurve, if set, goes to Adjust's toneCurve.
	ToneCurve []Point
	// AF, if set, adds the Af algorithm with the actuator's travel.
	AF *AFMap
}

// WriteYAML writes t as a libcamera software ISP tuning file.
func (t *Tuning) WriteYAML(w io.Writer) error {
	var b strings.Builder
	b.WriteString("# Generated by go-chromatix2libcamera from this device's vendor camera\n")
	b.WriteString("# tuning; do not redistribute. Sources:\n")
	for _, s := range t.Source {
		fmt.Fprintf(&b, "#   %s\n", s)
	}
	b.WriteString("%YAML 1.1\n---\nversion: 1\nalgorithms:\n")
	if t.BlackLevel > 0 {
		fmt.Fprintf(&b, "  - BlackLevel:\n      blackLevel: %d\n", t.BlackLevel)
	}
	b.WriteString("  - Awb:\n")
	if len(t.CCMs) > 0 {
		b.WriteString("  - Ccm:\n      ccms:\n")
		for _, c := range t.CCMs {
			fmt.Fprintf(&b, "        - ct: %d\n", c.CT)
			m := c.Matrix
			fmt.Fprintf(&b, "          ccm: [ %s, %s, %s,\n", f(m[0]), f(m[1]), f(m[2]))
			fmt.Fprintf(&b, "                 %s, %s, %s,\n", f(m[3]), f(m[4]), f(m[5]))
			fmt.Fprintf(&b, "                 %s, %s, %s ]\n", f(m[6]), f(m[7]), f(m[8]))
		}
	}
	b.WriteString("  - Adjust:\n")
	if len(t.ToneCurve) > 0 {
		b.WriteString("      toneCurve: [\n")
		for i, p := range t.ToneCurve {
			sep := ","
			if i == len(t.ToneCurve)-1 {
				sep = ""
			}
			fmt.Fprintf(&b, "        %.6f, %.6f%s\n", p.X, p.Y, sep)
		}
		b.WriteString("      ]\n")
	}
	b.WriteString("  - Agc:\n")
	if t.AF != nil {
		fmt.Fprintf(&b, "  # %s: stock drives codes %d (infinity) to %d (macro); the macro\n",
			t.AF.Actuator, t.AF.InfinityCode, t.AF.MacroCode)
		fmt.Fprintf(&b, "  # distance, %g dioptres, is from -macro-dioptres.\n", t.AF.MacroDioptres)
		fmt.Fprintf(&b, "  - Af:\n      map: [ 0.0, %d, %.1f, %d ]\n",
			t.AF.InfinityCode, t.AF.MacroDioptres, t.AF.MacroCode)
	}
	b.WriteString("...\n")
	_, err := io.WriteString(w, b.String())
	return err
}

func f(x float64) string {
	return fmt.Sprintf("%8.5f", x)
}
