package convert

import (
	"fmt"
	"io"
	"strings"
)

// Tuning is the content of a libcamera software ISP tuning file.
type Tuning struct {
	// Source names what the data was generated from, for the header.
	Source []string
	// BlackLevel is on libcamera's 16-bit scale; 0 leaves it out.
	BlackLevel int
	CCMs       []CCM
	// ToneCurve, if set, goes to Adjust's toneCurve.
	ToneCurve []Point
	// AF, if set, adds the Af algorithm with the actuator's travel.
	AF *AFMap
	// PDAF, if set with AF, adds the module's PDAF calibration to Af.
	PDAF *PDAF
}

// WriteYAML writes t as a libcamera software ISP tuning file.
func (t *Tuning) WriteYAML(w io.Writer) error {
	var b strings.Builder
	b.WriteString("# Generated by go-chromatix2libcamera from this device's vendor camera\n")
	b.WriteString("# tuning; do not redistribute. Sources:\n")
	for _, s := range t.Source {
		fmt.Fprintf(&b, "#   %s\n", s)
	}
	b.WriteString("%YAML 1.1\n---\nversion: 1\nalgorithms:\n")
	if t.BlackLevel > 0 {
		fmt.Fprintf(&b, "  - BlackLevel:\n      blackLevel: %d\n", t.BlackLevel)
	}
	b.WriteString("  - Awb:\n")
	if len(t.CCMs) > 0 {
		b.WriteString("  - Ccm:\n      ccms:\n")
		for _, c := range t.CCMs {
			fmt.Fprintf(&b, "        - ct: %d\n", c.CT)
			m := c.Matrix
			fmt.Fprintf(&b, "          ccm: [ %s, %s, %s,\n", f(m[0]), f(m[1]), f(m[2]))
			fmt.Fprintf(&b, "                 %s, %s, %s,\n", f(m[3]), f(m[4]), f(m[5]))
			fmt.Fprintf(&b, "                 %s, %s, %s ]\n", f(m[6]), f(m[7]), f(m[8]))
		}
	}
	b.WriteString("  - Adjust:\n")
	if len(t.ToneCurve) > 0 {
		b.WriteString("      toneCurve: [\n")
		for i, p := range t.ToneCurve {
			sep := ","
			if i == len(t.ToneCurve)-1 {
				sep = ""
			}
			fmt.Fprintf(&b, "        %.6f, %.6f%s\n", p.X, p.Y, sep)
		}
		b.WriteString("      ]\n")
	}
	b.WriteString("  - Agc:\n")
	if t.AF != nil && len(t.AF.Points) >= 2 {
		fmt.Fprintf(&b, "  # %s: %s\n", t.AF.Actuator, t.AF.Source)
		b.WriteString("  - Af:\n      map: [")
		for i, p := range t.AF.Points {
			if i > 0 {
				b.WriteString(",")
			}
			fmt.Fprintf(&b, " %.3f, %d", p.Dioptres, p.Code)
		}
		b.WriteString(" ]\n")
		if p := t.PDAF; p != nil {
			b.WriteString("      pdaf:\n")
			fmt.Fprintf(&b, "        # %s\n", p.Source)
			b.WriteString("        # Shading gains (1.0 = none) of the PD pixels that see the left\n")
			b.WriteString("        # and the right pupil half, grid points corner to corner.\n")
			fmt.Fprintf(&b, "        gainMap:\n          size: [ %d, %d ]\n", p.GainWidth, p.GainHeight)
			writeGrid(&b, "left", p.GainLeft, p.GainWidth, "%.3f")
			writeGrid(&b, "right", p.GainRight, p.GainWidth, "%.3f")
			b.WriteString("        # Lens movement in actuator codes per image pixel of phase, per region.\n")
			fmt.Fprintf(&b, "        dcc:\n          size: [ %d, %d ]\n", p.DCCWidth, p.DCCHeight)
			writeGrid(&b, "values", p.DCC, p.DCCWidth, "%.3f")
			if p.Offset != nil {
				b.WriteString("        # Phase offset correction, image pixels (sensor module)\n")
				fmt.Fprintf(&b, "        offset: %.4f\n", *p.Offset)
			}
		}
	}
	b.WriteString("...\n")
	_, err := io.WriteString(w, b.String())
	return err
}

// writeGrid writes a row-major grid as a flow list, one row per line.
func writeGrid(b *strings.Builder, key string, v []float64, width int, format string) {
	fmt.Fprintf(b, "          %s: [\n", key)
	for i, x := range v {
		if i%width == 0 {
			b.WriteString("           ")
		}
		b.WriteString(" " + fmt.Sprintf(format, x))
		if i < len(v)-1 {
			b.WriteString(",")
		}
		if i%width == width-1 || i == len(v)-1 {
			b.WriteString("\n")
		}
	}
	b.WriteString("          ]\n")
}

func f(x float64) string {
	return fmt.Sprintf("%8.5f", x)
}
