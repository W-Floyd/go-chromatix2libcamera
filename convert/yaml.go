package convert

import (
	"fmt"
	"io"
	"math"
	"strings"

	"github.com/W-Floyd/go-chromatix2libcamera/calibration"
)

// Tuning is the content of a libcamera software ISP tuning file.
type Tuning struct {
	// Source names what the data was generated from, for the header.
	Source []string
	// BlackLevel is on libcamera's 16-bit scale; 0 leaves it out.
	BlackLevel int
	// BlackLevelGain, if set, is the black level by sensor gain.
	BlackLevelGain []GainLevel
	CCMs           []CCM
	// CCMByLux, if set, is the matrices of every lux index region.
	CCMByLux []LuxCCMs
	// Denoise, if set, adds the Denoise algorithm.
	Denoise []DenoiseRegion
	// ToneCurveByLux and ChromaByLux, if set, are the output curve and
	// the chroma enhancement of every lux index region.
	ToneCurveByLux []LuxToneCurve
	ChromaByLux    []LuxChroma
	// Lux, if set with LumaZones, gives Agc a lux index model, which the
	// modules by lux index need.
	Lux *LuxModel
	// WhitePoints, if set, give Awb its colour temperature curve; OffLocus
	// are the reference points it has no colour temperature for.
	WhitePoints, OffLocus []WhitePoint
	// AWBCal, if set, is the unit calibration the white points include.
	AWBCal *calibration.AWB
	// GainAdjust, if set, gives Awb its gain adjustment.
	GainAdjust *GainAdjust
	// ToneCurve, if set, goes to Adjust's toneCurve.
	ToneCurve []Point
	// AF, if set, adds the Af algorithm with the actuator's travel.
	AF *AFMap
	// PDAF, if set with AF, adds the module's PDAF calibration to Af.
	PDAF *PDAF
	// LumaZones, if set, give Agc a mean luminance target: the
	// brightest zone's, as the soft IPA has no lux estimate.
	LumaZones []LumaZone
	// Hist, if set with LumaZones, gives Agc the histogram adjustment of
	// the target, again from the brightest zone.
	Hist *HistTarget
	// LSC, if set, adds the Lsc algorithm's lens shading gains.
	LSC *LSC
	// Chroma, if set, gives Adjust its chroma scales.
	Chroma []ChromaSet
	// DRC, if set, gives Adjust its DRC tone mapping.
	DRC *DRCCurve
}

// LuxModel is the soft ISP's model of the lux index: see Options.
type LuxModel struct {
	RefProduct, PerStop float64
}

// WriteYAML writes t as a libcamera software ISP tuning file.
func (t *Tuning) WriteYAML(w io.Writer) error {
	var b strings.Builder
	b.WriteString("# Generated by go-chromatix2libcamera from this device's vendor camera\n")
	b.WriteString("# tuning; do not redistribute. Sources:\n")
	for _, s := range t.Source {
		fmt.Fprintf(&b, "#   %s\n", s)
	}
	b.WriteString("%YAML 1.1\n---\nversion: 1\nalgorithms:\n")
	if t.BlackLevel > 0 {
		fmt.Fprintf(&b, "  - BlackLevel:\n      blackLevel: %d\n", t.BlackLevel)
		if len(t.BlackLevelGain) > 0 {
			b.WriteString("      # By sensor gain (demuxblklevel14's gain regions): gain, level\n")
			b.WriteString("      blackLevelGain: [")
			for i, p := range t.BlackLevelGain {
				if i > 0 {
					b.WriteString(",")
				}
				fmt.Fprintf(&b, " %.4g, %.0f", p.Gain, p.Level)
			}
			b.WriteString(" ]\n")
		}
	}
	b.WriteString("  - Awb:\n")
	if len(t.WhitePoints) > 0 {
		b.WriteString("      # AWB reference points (refPtV1) on CamX's daylight locus, as\n")
		b.WriteString("      # the gains that make each grey:")
		for _, p := range t.WhitePoints {
			fmt.Fprintf(&b, " %s", p.Name)
		}
		b.WriteString("\n")
		if c := t.AWBCal; c != nil {
			rg, bg := c.Factors()
			fmt.Fprintf(&b, "      # Scaled to this unit (EEPROM): R/G x %.4f, B/G x %.4f\n", rg, bg)
			fmt.Fprintf(&b, "      #   (unit %.4f %.4f, golden %.4f %.4f)\n",
				c.UnitRG, c.UnitBG, c.GoldenRG, c.GoldenBG)
		}
		if len(t.OffLocus) > 0 {
			b.WriteString("      # Off the locus (R/G, B/G):")
			for _, p := range t.OffLocus {
				fmt.Fprintf(&b, " %s %.4f %.4f", p.Name, p.RG, p.BG)
			}
			b.WriteString("\n")
		}
		b.WriteString("      colourGains:\n")
		for _, p := range t.WhitePoints {
			r, bl := p.Gains()
			fmt.Fprintf(&b, "        - ct: %d\n          gains: [ %.4f, %.4f ]\n", p.CT, r, bl)
		}
		pos, neg := Transverse(t.WhitePoints, t.OffLocus)
		b.WriteString("      # How far grey world may stray off the locus, by colour temperature:\n")
		fmt.Fprintf(&b, "      # to the off-locus points where they are, %g elsewhere. [ ct, width, ... ]\n", MinTransverse)
		for _, s := range []struct {
			key  string
			band []BandPoint
		}{{"transversePos", pos}, {"transverseNeg", neg}} {
			fmt.Fprintf(&b, "      %s: [", s.key)
			for i, p := range s.band {
				if i > 0 {
					b.WriteString(",")
				}
				fmt.Fprintf(&b, " %d, %.4f", p.CT, p.Width)
			}
			b.WriteString(" ]\n")
		}
		if a := t.GainAdjust; a != nil && len(a.Vertices) > 0 && len(a.Triangles) > 0 {
			b.WriteString("      # Gain adjustment (triglGAV1) at the lux index: factors on the red\n")
			b.WriteString("      # and blue gains, interpolated over a mesh of white points and by\n")
			b.WriteString("      # colour temperature, which keep some of warm light's warmth.\n")
			b.WriteString("      gainAdjust:\n        vertices: [  # R/G, B/G, red, blue\n")
			for i, v := range a.Vertices {
				sep := ","
				if i == len(a.Vertices)-1 {
					sep = ""
				}
				fmt.Fprintf(&b, "          %.4f, %.4f, %.4f, %.4f%s\n", v.RG, v.BG, v.R, v.B, sep)
			}
			b.WriteString("        ]\n        triangles: [")
			for i, tri := range a.Triangles {
				if i > 0 {
					b.WriteString(",")
				}
				if i%8 == 0 {
					b.WriteString("\n         ")
				}
				fmt.Fprintf(&b, " %d, %d, %d", tri[0], tri[1], tri[2])
			}
			b.WriteString("\n        ]\n")
			if len(a.CCT) > 0 {
				for _, s := range []struct {
					key string
					val func(AdjustPoint) float64
				}{{"cctRed", func(p AdjustPoint) float64 { return p.R }}, {"cctBlue", func(p AdjustPoint) float64 { return p.B }}} {
					fmt.Fprintf(&b, "        %s: [", s.key)
					for i, p := range a.CCT {
						if i > 0 {
							b.WriteString(",")
						}
						fmt.Fprintf(&b, " %g, %.3f", p.CT, s.val(p))
					}
					b.WriteString(" ]\n")
				}
			}
		}
	}
	if len(t.CCMs) > 0 {
		b.WriteString("  - Ccm:\n      ccms:\n")
		writeCCMs(&b, "        ", t.CCMs)
		if len(t.CCMByLux) > 0 {
			b.WriteString("      # The same by lux index (cc13's AEC regions), which Agc estimates;\n")
			b.WriteString("      # between regions' ranges the matrices blend. Without a lux\n")
			b.WriteString("      # estimate, the ccms above apply.\n")
			b.WriteString("      luxSets:\n")
			for _, r := range t.CCMByLux {
				fmt.Fprintf(&b, "        - lux: [ %g, %g ]\n          ccms:\n", r.Start, r.End)
				writeCCMs(&b, "            ", r.CCMs)
			}
		}
	}
	if l := t.LSC; l != nil && len(l.Sets) > 0 {
		b.WriteString("  - Lsc:\n")
		if l.Calibrated {
			b.WriteString("      # Scaled to this unit (EEPROM): golden module level over the unit's\n")
		}
		fmt.Fprintf(&b, "      grid: [ %d, %d ]\n      sets:\n", l.Width, l.Height)
		writeLSCSets(&b, "        ", l.Sets, l.Width)
		if len(l.ByLux) > 0 && t.Lux != nil {
			b.WriteString("      # The same by lux index (the module's AEC regions), as Ccm's luxSets\n")
			b.WriteString("      luxSets:\n")
			for _, r := range l.ByLux {
				fmt.Fprintf(&b, "        - lux: [ %g, %g ]\n          sets:\n", r.Start, r.End)
				writeLSCSets(&b, "            ", r.Sets, l.Width)
			}
		}
	}
	if len(t.Denoise) > 0 {
		b.WriteString("  - Denoise:\n")
		b.WriteString("      # The adaptive Bayer filter (bpcabf41) by gain: the noise model (variance of the\n")
		b.WriteString("      # 12-bit signal = noise x level / 64, from the sensor's noise table) and the\n")
		b.WriteString("      # filter strengths (smaller is stronger) for R/B and Gr/Gb at and below, and at\n")
		b.WriteString("      # and above, the anchors' levels (taken to be 10-bit counts above black).\n")
		b.WriteString("      regions:\n")
		for _, d := range t.Denoise {
			fmt.Fprintf(&b, "        - gain: [ %.4g, %.4g ]\n          noise: %.5g\n", d.GainStart, d.GainEnd, d.NoiseK)
			fmt.Fprintf(&b, "          strengthLo: [ %.3g, %.3g ]\n          strengthHi: [ %.3g, %.3g ]\n",
				d.StrengthLo[0], d.StrengthLo[1], d.StrengthHi[0], d.StrengthHi[1])
			fmt.Fprintf(&b, "          anchors: [ %.4g, %.4g ]\n", d.AnchorLo, d.AnchorHi)
		}
	}
	b.WriteString("  - Adjust:\n")
	if len(t.ToneCurve) > 0 {
		b.WriteString("      toneCurve: [\n")
		writeTonePoints(&b, "        ", t.ToneCurve)
		b.WriteString("      ]\n")
		if len(t.ToneCurveByLux) > 0 && t.Lux != nil {
			b.WriteString("      # The same by lux index (gamma15's AEC regions), as Ccm's luxSets\n")
			b.WriteString("      toneCurveLux:\n")
			for _, r := range t.ToneCurveByLux {
				fmt.Fprintf(&b, "        - lux: [ %g, %g ]\n          toneCurve: [\n", r.Start, r.End)
				writeTonePoints(&b, "            ", r.Curve)
				b.WriteString("          ]\n")
			}
		}
	}
	if d := t.DRC; d != nil {
		b.WriteString("      # DRC tone mapping (tmc12_sw's anchor knee points), by DRC gain.\n")
		fmt.Fprintf(&b, "      # CamX applies %.0f%% of it (in log) globally and the rest by local\n", 100*d.GTMShare)
		b.WriteString("      # tone mapping, which the soft ISP lacks: all of it applies here.\n")
		b.WriteString("      drcCurve:\n")
		writeDRC(&b, "        ", d)
		if len(d.ByLux) > 0 && t.Lux != nil {
			b.WriteString("      # The same by lux index (tmc12's AEC regions), as Ccm's luxSets\n")
			b.WriteString("      drcCurveLux:\n")
			for _, r := range d.ByLux {
				fmt.Fprintf(&b, "        - lux: [ %g, %g ]\n          drcCurve:\n", r.Start, r.End)
				writeDRC(&b, "            ", r.Curve)
			}
		}
	}
	if len(t.Chroma) > 0 {
		b.WriteString("      # Chroma enhancement (cv12) after the tone curve, on BT.601\n")
		b.WriteString("      # chroma by sign: Cb+ (blue), Cb- (yellow), Cr+ (red), Cr- (green)\n")
		b.WriteString("      chroma:\n")
		writeChroma(&b, "        ", t.Chroma)
		if len(t.ChromaByLux) > 0 && t.Lux != nil {
			b.WriteString("      # The same by lux index (cv12's AEC regions), as Ccm's luxSets\n")
			b.WriteString("      chromaLux:\n")
			for _, r := range t.ChromaByLux {
				fmt.Fprintf(&b, "        - lux: [ %g, %g ]\n          chroma:\n", r.Start, r.End)
				writeChroma(&b, "            ", r.Sets)
			}
		}
	}
	b.WriteString("  - Agc:\n")
	if len(t.LumaZones) > 0 {
		z := t.LumaZones[0]
		b.WriteString("      # AEC luma target (8-bit linear) by lux index zone:\n      #")
		for _, lz := range t.LumaZones {
			fmt.Fprintf(&b, " %g-%g: %g", lz.Start, lz.End, lz.Target)
		}
		b.WriteString("\n      # The brightest zone's, as a fraction of full scale:\n")
		fmt.Fprintf(&b, "      meanTarget: %.4f\n", z.Target/AECLumaFullScale)
		if l := t.Lux; l != nil {
			b.WriteString("      # CamX's lux index, which selects the tables by lux index, from the\n")
			b.WriteString("      # tuning's exposure table (expKneeEntries): exposure time (us) x gain\n")
			b.WriteString("      # at index 250, and index steps per stop of scene brightness.\n")
			fmt.Fprintf(&b, "      lux:\n        refProduct: %.6g\n        perStop: %.6g\n", l.RefProduct, l.PerStop)
		}
		if h := t.Hist; h != nil && h.Enable && h.ADRC && len(h.Zones) > 0 {
			hz := h.Zones[0]
			b.WriteString("      # Histogram luma target, brightest zone (lux index ")
			fmt.Fprintf(&b, "%g-%g): satRefHigh %g,\n", hz.Start, hz.End, hz.SatRefHigh)
			b.WriteString("      # G ranges, ADRC gain; DRC gain by zone:")
			for _, z := range h.Zones {
				fmt.Fprintf(&b, " %.4g", math.Min(z.MaxDRCGain, z.MaxADRCGain))
			}
			b.WriteString("\n      histogram:\n")
			fmt.Fprintf(&b, "        satRef: %.4f\n", hz.SatRefHigh/AECLumaFullScale)
			fmt.Fprintf(&b, "        satRange: [ %.4g, %.4g ]\n", hz.SatPushdownRange[1][0], hz.SatPushdownRange[1][1])
			fmt.Fprintf(&b, "        pushupRange: [ %.4g, %.4g ]\n", hz.SatPushupRange[1][0], hz.SatPushupRange[1][1])
			fmt.Fprintf(&b, "        targetAdj: [ %.4g, %.4g ]\n", hz.MinTargetAdjRatio, hz.MaxTargetAdjRatio)
			fmt.Fprintf(&b, "        maxDrcGain: %.4g\n", math.Min(hz.MaxDRCGain, hz.MaxADRCGain))
			fmt.Fprintf(&b, "        filter: %.4g\n", h.Filter)
			if h.DarkBoost && hz.MaxDarkBoostGain > 1 {
				fmt.Fprintf(&b, "        # Dark boost: darkest G pixels' floor (darkRefLow %g of %g), lifted by\n",
					hz.DarkRefLow, AECLumaFullScale)
				b.WriteString("        # the tone curve by at most maxDarkBoost more than the DRC gain\n")
				fmt.Fprintf(&b, "        darkRef: %.4f\n", hz.DarkRefLow/AECLumaFullScale)
				fmt.Fprintf(&b, "        darkRange: [ %.4g, %.4g ]\n", hz.DarkRange[1][0], hz.DarkRange[1][1])
				fmt.Fprintf(&b, "        maxDarkBoost: %.4g\n", hz.MaxDarkBoostGain)
			}
		}
	}
	if t.AF != nil && len(t.AF.Points) >= 2 {
		fmt.Fprintf(&b, "  # %s: %s\n", t.AF.Actuator, t.AF.Source)
		b.WriteString("  - Af:\n      map: [")
		for i, p := range t.AF.Points {
			if i > 0 {
				b.WriteString(",")
			}
			fmt.Fprintf(&b, " %.3f, %d", p.Dioptres, p.Code)
		}
		b.WriteString(" ]\n")
		if p := t.PDAF; p != nil {
			b.WriteString("      pdaf:\n")
			fmt.Fprintf(&b, "        # %s\n", p.Source)
			b.WriteString("        # Shading gains (1.0 = none) of the PD pixels that see the left\n")
			b.WriteString("        # and the right pupil half, grid points corner to corner.\n")
			fmt.Fprintf(&b, "        gainMap:\n          size: [ %d, %d ]\n", p.GainWidth, p.GainHeight)
			writeGrid(&b, "left", p.GainLeft, p.GainWidth, "%.3f")
			writeGrid(&b, "right", p.GainRight, p.GainWidth, "%.3f")
			b.WriteString("        # Lens movement in actuator codes per image pixel of phase, per region.\n")
			fmt.Fprintf(&b, "        dcc:\n          size: [ %d, %d ]\n", p.DCCWidth, p.DCCHeight)
			writeGrid(&b, "values", p.DCC, p.DCCWidth, "%.3f")
			if p.Offset != nil {
				b.WriteString("        # Phase offset correction, image pixels (sensor module)\n")
				fmt.Fprintf(&b, "        offset: %.4f\n", *p.Offset)
			}
		}
	}
	b.WriteString("...\n")
	_, err := io.WriteString(w, b.String())
	return err
}

// writeLSCSets writes lens shading sets as a list at an indent.
func writeLSCSets(b *strings.Builder, indent string, sets []LSCSet, width int) {
	for _, s := range sets {
		fmt.Fprintf(b, "%s- ct: %d\n", indent, s.CT)
		writeGridAt(b, indent+"  ", "r", s.R, width, "%.3f")
		writeGridAt(b, indent+"  ", "g", s.G, width, "%.3f")
		writeGridAt(b, indent+"  ", "b", s.B, width, "%.3f")
	}
}

// writeTonePoints writes a tone curve's points, one pair to a line.
func writeTonePoints(b *strings.Builder, indent string, pts []Point) {
	for i, p := range pts {
		sep := ","
		if i == len(pts)-1 {
			sep = ""
		}
		fmt.Fprintf(b, "%s%.6f, %.6f%s\n", indent, p.X, p.Y, sep)
	}
}

// writeDRC writes a DRC tone mapping's keys at an indent.
func writeDRC(b *strings.Builder, indent string, d *DRCCurve) {
	fmt.Fprintf(b, "%smaxRatio: %g\n%sanchors:\n", indent, d.MaxRatio, indent)
	for _, a := range d.Anchors {
		fmt.Fprintf(b, "%s  - drcGain: %.4g\n%s    tones: [ %.3f, %.3f, %.3f ]\n%s    darkBoost: %.3f\n%s    darkBoostRatio: %.3f\n",
			indent, a.DRCGain, indent, a.Dark, a.Mid, a.Bright, indent, a.DarkBoost, indent, a.DarkBoostRatio)
	}
}

// writeChroma writes chroma enhancement sets as a list at an indent.
func writeChroma(b *strings.Builder, indent string, sets []ChromaSet) {
	for _, c := range sets {
		fmt.Fprintf(b, "%s- ct: %d\n%s  scale: [ %.3f, %.3f, %.3f, %.3f ]\n",
			indent, c.CT, indent, c.Scale[0], c.Scale[1], c.Scale[2], c.Scale[3])
		fmt.Fprintf(b, "%s  shear: [ %.4f, %.4f, %.4f, %.4f ]\n",
			indent, c.Shear[0], c.Shear[1], c.Shear[2], c.Shear[3])
	}
}

// writeCCMs writes colour correction matrices as a list at an indent.
func writeCCMs(b *strings.Builder, indent string, ccms []CCM) {
	for _, c := range ccms {
		fmt.Fprintf(b, "%s- ct: %d\n", indent, c.CT)
		m := c.Matrix
		fmt.Fprintf(b, "%s  ccm: [ %s, %s, %s,\n", indent, f(m[0]), f(m[1]), f(m[2]))
		fmt.Fprintf(b, "%s         %s, %s, %s,\n", indent, f(m[3]), f(m[4]), f(m[5]))
		fmt.Fprintf(b, "%s         %s, %s, %s ]\n", indent, f(m[6]), f(m[7]), f(m[8]))
	}
}

// writeGrid writes a row-major grid as a flow list, one row per line.
func writeGrid(b *strings.Builder, key string, v []float64, width int, format string) {
	writeGridAt(b, "          ", key, v, width, format)
}

// writeGridAt is writeGrid at an indent.
func writeGridAt(b *strings.Builder, indent, key string, v []float64, width int, format string) {
	fmt.Fprintf(b, "%s%s: [\n", indent, key)
	for i, x := range v {
		if i%width == 0 {
			b.WriteString(indent + " ")
		}
		b.WriteString(" " + fmt.Sprintf(format, x))
		if i < len(v)-1 {
			b.WriteString(",")
		}
		if i%width == width-1 || i == len(v)-1 {
			b.WriteString("\n")
		}
	}
	b.WriteString(indent + "]\n")
}

func f(x float64) string {
	return fmt.Sprintf("%8.5f", x)
}
